/**
 * scripts/verify-api-ids.mjs
 *
 * Records a provider's exact API model string only when its own documentation
 * proves it.
 *
 * The rule is deliberately narrow, because a wrong id is a broken integration:
 *
 *   1. the record must link an official API documentation page;
 *   2. the page path must end in the model id (`/models/gpt-6.2-astra`), which is
 *      how OpenAI, Google and several others publish one page per model;
 *   3. the fetched page must return 200 AND contain that exact string.
 *
 * Pages whose last path segment is `overview`, `pricing`, `docs` and so on are
 * skipped: a generic page is not evidence of a specific model string. Nothing is
 * derived from a display name, and a model with no qualifying page simply keeps
 * no canonical API id.
 *
 *   node scripts/verify-api-ids.mjs            fetch and write data/api-ids.ts
 *   node scripts/verify-api-ids.mjs --dry-run  report only
 *
 * After a refresh: npm run validate && npm run snapshot && npm test
 */
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const { load, ROOT } = require("./lib/ts-load.js")
const { modelsData } = load("data/models.ts")

const OUT = path.join(ROOT, "data", "api-ids.ts")
const UA = "ModelRegistry-Verify/1.0 (+https://modelregistry.tirup.in/verify)"
const DRY = process.argv.includes("--dry-run")
const TIMEOUT_MS = 20000

const GENERIC = new Set([
  "overview",
  "pricing",
  "docs",
  "models",
  "api",
  "reference",
  "quickstart",
  "changelog",
  "news",
  "guides",
  "blog",
  "index",
])

/** A plausible model id: lowercase, hyphens, at least one digit. */
const MODEL_ID = /^[a-z][a-z0-9]*(?:[.-][a-z0-9]+)+$/

function candidateFor(url) {
  let parsed
  try {
    parsed = new URL(url)
  } catch {
    return null
  }
  const segments = parsed.pathname.split("/").filter(Boolean)
  const last = segments.at(-1)
  if (!last) return null
  const candidate = decodeURIComponent(last)
  if (GENERIC.has(candidate.toLowerCase())) return null
  if (!MODEL_ID.test(candidate)) return null
  if (!/\d/.test(candidate)) return null
  return candidate
}

async function prove(url, candidate) {
  try {
    const res = await fetch(url, {
      headers: { "user-agent": UA, accept: "text/html" },
      signal: AbortSignal.timeout(TIMEOUT_MS),
    })
    if (!res.ok) return { ok: false, reason: `HTTP ${res.status}` }
    const text = await res.text()
    if (!text.includes(candidate)) return { ok: false, reason: "string not on page" }
    return { ok: true }
  } catch (error) {
    return { ok: false, reason: error.message }
  }
}

const verified = []
const skipped = []
const failed = []

for (const model of modelsData) {
  const url = model.links.apiDocs
  if (!url) {
    skipped.push({ slug: model.id, reason: "no API documentation link" })
    continue
  }
  const candidate = candidateFor(url)
  if (!candidate) {
    skipped.push({ slug: model.id, reason: "generic documentation page" })
    continue
  }
  const result = await prove(url, candidate)
  if (result.ok) {
    verified.push({ modelId: model.id, id: candidate, sourceUrl: url })
    console.log(`  ok   ${model.id.padEnd(30)} ${candidate}`)
  } else {
    failed.push({ slug: model.id, url, reason: result.reason })
    console.log(`  skip ${model.id.padEnd(30)} ${candidate} (${result.reason})`)
  }
}

const retrievedAt = new Date().toISOString().slice(0, 10)
const sorted = verified.sort((a, b) => a.modelId.localeCompare(b.modelId))

console.log(`\n${sorted.length} verified, ${skipped.length} skipped, ${failed.length} unproven.`)

if (failed.length > 0) {
  console.log("\nUnproven (no canonical id recorded):")
  for (const entry of failed) console.log(`  - ${entry.slug}: ${entry.reason} (${entry.url})`)
}

const file = `/**
 * data/api-ids.ts - GENERATED by scripts/verify-api-ids.mjs. Do not edit.
 *
 * Exact provider model strings, recorded only when the provider's own model page
 * both ends in that id and contains it. A model with no entry has no verified
 * string; its canonical record reports an empty list rather than a guess.
 */
export interface ProviderApiId {
  modelId: string
  id: string
  sourceUrl: string
  verifiedAt: string
}

export const providerApiIds: ProviderApiId[] = ${JSON.stringify(
  sorted.map((entry) => ({ ...entry, verifiedAt: retrievedAt })),
  null,
  2,
)}
`

if (DRY) {
  console.log("\nDry run: nothing written.")
  process.exit(0)
}

fs.writeFileSync(OUT, file)
console.log(`\nWrote ${path.relative(ROOT, OUT)} (${sorted.length} ids).`)
console.log("Next: npm run validate && npm run snapshot && npm test")
