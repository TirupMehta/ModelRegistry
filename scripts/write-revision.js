/**
 * scripts/write-revision.js
 * Derives the machine-readable dataset revision from the actual data files.
 * Rewrites data/revision.ts ONLY when tracked data content changed, so
 * `revisedAt` reflects a real data revision — never the build time.
 *
 * Data files hashed: data/models.ts, data/companies.ts, data/leaderboard.ts.
 * Consumed by: /api/v1/models (updatedAt/datasetVersion), /api/check-updates,
 * /llms.txt, /llms-full.txt, sitemap lastmod values, JSON feed.
 */
const fs = require("fs")
const path = require("path")
const crypto = require("crypto")

const DATA_FILES = ["../data/models.ts", "../data/companies.ts", "../data/leaderboard.ts"]
const OUT_PATH = path.resolve(__dirname, "../data/revision.ts")

function todayUTC() {
  return new Date().toISOString().slice(0, 10)
}

function readExisting() {
  try {
    const src = fs.readFileSync(OUT_PATH, "utf8")
    const ver = (src.match(/datasetVersion:\s*"([^"]+)"/) || [])[1]
    const rev = (src.match(/revisedAt:\s*"([^"]+)"/) || [])[1]
    const hash = (src.match(/contentHash:\s*"([^"]+)"/) || [])[1]
    if (ver && rev && hash) return { datasetVersion: ver, revisedAt: rev, contentHash: hash }
  } catch {
    // No revision file yet — will be created.
  }
  return null
}

function main() {
  const hash = crypto.createHash("sha256")
  for (const rel of DATA_FILES) {
    hash.update(fs.readFileSync(path.resolve(__dirname, rel)))
  }
  const contentHash = hash.digest("hex").slice(0, 16)
  const existing = readExisting()
  if (existing && existing.contentHash === contentHash) {
    console.log(`✔ Dataset revision unchanged (${existing.datasetVersion}, revised ${existing.revisedAt}).`)
    return
  }
  const today = todayUTC().replace(/-/g, ".")
  let datasetVersion = today
  if (existing && existing.datasetVersion.startsWith(today)) {
    const m = existing.datasetVersion.match(/-r(\d+)$/)
    datasetVersion = `${today}-r${m ? parseInt(m[1], 10) + 1 : 2}`
  }
  const out = `/**
 * data/revision.ts — GENERATED by scripts/write-revision.js. Do not edit.
 * The revision advances only when data/models.ts, data/companies.ts or
 * data/leaderboard.ts content changes. Consumers must treat revisedAt as the
 * dataset's last real change, never as a build timestamp.
 */
export const datasetRevision = {
  datasetVersion: ${JSON.stringify(datasetVersion)},
  revisedAt: ${JSON.stringify(todayUTC())},
  contentHash: ${JSON.stringify(contentHash)},
  sourceAudit: "docs/audit-2026-10-07.md",
} as const
`
  fs.writeFileSync(OUT_PATH, out)
  console.log(`✔ Dataset revision advanced to ${datasetVersion}.`)
}

main()
