#!/usr/bin/env node

/**
 * scripts/sync-readme.js
 * Automatically synchronizes the frontier models table in README.md from data/models.ts.
 * Ensures contributors only ever need to edit data/models.ts.
 */

const fs = require("fs")
const path = require("path")
const ts = require("typescript")
const vm = require("vm")

function loadTsModule(relPath, registry = {}) {
  const fullPath = path.resolve(__dirname, relPath)
  const source = fs.readFileSync(fullPath, "utf8")
  const transpiled = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText

  const mod = { exports: {} }
  const ctx = vm.createContext({
    module: mod,
    exports: mod.exports,
    require: (spec) => {
      if (spec in registry) return registry[spec]
      return require(spec)
    },
    console,
  })
  vm.runInContext(transpiled, ctx)
  return mod.exports
}

const { modelsData } = loadTsModule("../data/models.ts")
const { companies } = loadTsModule("../data/companies.ts")

function formatContext(tokens) {
  if (!tokens) return "-"
  if (tokens >= 1000000) {
    const val = tokens / 1000000
    if (Math.abs(val - 1.048576) < 0.06 || Math.abs(val - 1) < 0.01) return "1M"
    return `${val.toFixed(2).replace(/\.?0+$/, "")}M`
  }
  if (tokens >= 1000) {
    const thousands = Math.round(tokens / 1000)
    return `${thousands}k`
  }
  return String(tokens)
}

function formatPricing(model) {
  if (model.pricingUnit) {
    const unitBase =
      model.pricing.input === model.pricing.output
        ? `$${model.pricing.input}`
        : `$${model.pricing.input} in / $${model.pricing.output}`
    return `${unitBase} ${model.pricingUnit}`
  }
  const base = `$${model.pricing.input} in / $${model.pricing.output} out`
  if (model.openWeights) {
    return `${base} *(Open)*`
  }
  return base
}

function generateMarkdownTable() {
  const companyKeys = Object.keys(companies)

  const rows = companyKeys.map((companyId) => {
    const company = companies[companyId]
    const flagship = modelsData.find((m) => m.companyId === companyId && m.isCompanyFlagship)
    // Only a genuine latest checkpoint earns this cell, and it is resolved by
    // date - never by array order, which is what made this column drift when a
    // lab briefly carried more than one flag. `isLatestCheckpoint` may coincide
    // with the flagship (see /docs); when it does, the cell stays empty rather
    // than repeating the flagship in the next column over.
    const latestDrop = modelsData
      .filter((m) => m.companyId === companyId && m.isLatestCheckpoint && m.id !== flagship?.id)
      .sort((a, b) => b.releaseDate.localeCompare(a.releaseDate))[0]

    const flagshipCell = flagship
      ? `[${flagship.name}](https://modelregistry.tirup.in/models/${flagship.id})`
      : "-"

    const latestDropCell = latestDrop
      ? `[${latestDrop.name}](https://modelregistry.tirup.in/models/${latestDrop.id})`
      : "-"

    const contextCell = flagship ? formatContext(flagship.contextWindowTokens) : "-"
    const licenseCell = flagship?.openWeights
      ? `Open (${flagship.license.replace(/ License| \/ .*$/g, "")})`
      : "Proprietary"
    const pricingCell = flagship ? formatPricing(flagship) : "-"

    return `| [**${company.name}**](${company.website}) | ${flagshipCell} | ${latestDropCell} | ${contextCell} | ${licenseCell} | ${pricingCell} |`
  })

  const header = [
    "| Laboratory | Primary Flagship | Latest Checkpoint | Context | Access | Pricing |",
    "|:---|:---|:---|:---|:---|:---|",
  ]

  // One line of prose replaces what would otherwise read as ten empty cells.
  // House style bans the em dash, so this stays ASCII.
  const footnote =
    "\nWhere Latest Checkpoint is empty, the lab's newest release *is* its flagship (already listed to the left).\n"

  return [...header, ...rows].join("\n") + footnote
}

function syncReadme(checkOnly = false) {
  const readmePath = path.resolve(__dirname, "../README.md")
  // Generators always emit LF: Windows checkouts carry CRLF, and splicing an
  // LF table into CRLF content produced mixed-EOL files that kept showing up
  // as dirty in git. Normalizing on read makes the output byte-identical on
  // every OS (see .gitattributes).
  const rawReadme = fs.readFileSync(readmePath, "utf8")
  const readmeContent = rawReadme.replace(/\r\n/g, "\n")

  const startMarker = "<!-- REGISTRY_TABLE_START -->"
  const endMarker = "<!-- REGISTRY_TABLE_END -->"

  const startIndex = readmeContent.indexOf(startMarker)
  const endIndex = readmeContent.indexOf(endMarker)

  if (startIndex === -1 || endIndex === -1) {
    console.error("❌ Could not find <!-- REGISTRY_TABLE_START --> and <!-- REGISTRY_TABLE_END --> markers in README.md")
    process.exit(1)
  }

  const tableMarkdown = generateMarkdownTable()
  const newSection = `${startMarker}\n<!-- Auto-generated by scripts/sync-readme.js - Do not edit manually -->\n${tableMarkdown}\n`

  const updatedReadme = readmeContent.slice(0, startIndex) + newSection + readmeContent.slice(endIndex)

  if (checkOnly) {
    if (readmeContent !== updatedReadme) {
      console.error("❌ README.md frontier models table is out of date! Run: node scripts/sync-readme.js")
      process.exit(1)
    } else {
      console.log("✔ README.md frontier models table is up to date.")
      process.exit(0)
    }
  }

  if (rawReadme !== updatedReadme) {
    fs.writeFileSync(readmePath, updatedReadme, "utf8")
    console.log("✔ Successfully synchronized README.md frontier models table.")
  } else {
    console.log("✔ README.md is already up to date with data/models.ts.")
  }

  syncContributePrompt()
}

/**
 * Injects the agent contribution prompt (single-sourced from
 * lib/agent-prompts.ts) between CONTRIBUTE_PROMPT markers. Same
 * write-if-changed semantics as the table sync above.
 */
function syncContributePrompt() {
  const datasetRegistry = {
    "../data/models": { modelsData },
    "@/data/models": { modelsData },
    "../data/companies": { companies },
    "@/data/companies": { companies },
  }
  const { buildContributePrompt, CONTRIBUTE_PROMPT_VERSION } = loadTsModule("../lib/agent-prompts.ts", datasetRegistry)

  const readmePath = path.resolve(__dirname, "../README.md")
  const rawReadme = fs.readFileSync(readmePath, "utf8")
  let readmeContent = rawReadme.replace(/\r\n/g, "\n")

  const startMarker = "<!-- CONTRIBUTE_PROMPT_START -->"
  const endMarker = "<!-- CONTRIBUTE_PROMPT_END -->"

  const startIndex = readmeContent.indexOf(startMarker)
  const endIndex = readmeContent.indexOf(endMarker)

  if (startIndex === -1 || endIndex === -1) {
    console.error("❌ Could not find <!-- CONTRIBUTE_PROMPT_START --> and <!-- CONTRIBUTE_PROMPT_END --> markers in README.md")
    process.exit(1)
  }

  const prompt = buildContributePrompt()
  const newSection =
    `${startMarker}\n<!-- Auto-generated from lib/agent-prompts.ts (${CONTRIBUTE_PROMPT_VERSION}) - Do not edit manually -->\n` +
    `Paste this into any AI agent (Claude, Cursor, Codex, Copilot) and it will walk you through contributing:\n\n` +
    "```text\n" + prompt + "\n```\n"

  const updatedReadme = readmeContent.slice(0, startIndex) + newSection + readmeContent.slice(endIndex)

  if (rawReadme !== updatedReadme) {
    fs.writeFileSync(readmePath, updatedReadme, "utf8")
    console.log("✔ Successfully synchronized README.md agent prompt.")
  } else {
    console.log("✔ README.md agent prompt is already up to date.")
  }
}

const checkOnly = process.argv.includes("--check")
syncReadme(checkOnly)
