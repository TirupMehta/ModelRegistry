/**
 * scripts/build-irt.mjs
 *
 * Fits the regularized 2PL IRT model over data/benchmarks.ts and writes
 * data/irt-scores.ts.
 *
 *   node scripts/build-irt.mjs            write
 *   node scripts/build-irt.mjs --check    exit 1 if the committed output is stale
 *   node scripts/build-irt.mjs --explain  print the fit diagnostics and stop
 *
 * Deterministic: the reference date is the dataset revision, never the clock, and
 * the anchors are frozen. The same observations always produce the same file,
 * which is what lets the snapshot manifest cover this output.
 */
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const { load, ROOT } = require("./lib/ts-load.js")

const { modelsData } = load("data/models.ts")
const { datasetRevision } = load("data/revision.ts")
const { benchmarkObservations } = load("data/benchmarks.ts")
const { IRT_ANCHORS, IRT_SCALE } = load("data/irt-anchors.ts")
const { fitIrt, IRT_VERSION } = load("lib/irt.ts")

const OUT = path.join(ROOT, "data", "irt-scores.ts")
const CHECK = process.argv.includes("--check")
const EXPLAIN = process.argv.includes("--explain")

/**
 * Blended cost per 1M tokens at the 3:1 input:output mix the board documents.
 * Only USD, per-token pricing is comparable; a per-second or non-USD price is
 * left null rather than converted.
 */
const blendedCostUsd = {}
for (const model of modelsData) {
  const perToken = model.pricingUnit === undefined || model.pricingUnit === "per 1M tokens"
  const usd = model.pricingCurrency === undefined
  const { input, output } = model.pricing
  if (!perToken || !usd || typeof input !== "number" || typeof output !== "number") {
    blendedCostUsd[model.id] = null
    continue
  }
  blendedCostUsd[model.id] = Math.round(((3 * input + output) / 4) * 10000) / 10000
}

const asOf = datasetRevision.revisedAt
const result = fitIrt(benchmarkObservations, { asOf, anchors: IRT_ANCHORS, blendedCostUsd })

const explainRows = result.models.map((row) => ({
  slug: row.slug,
  index: row.index,
  theta: row.theta,
  se: row.se,
  ci: row.ci90,
  n: row.observations,
  status: row.confidenceStatus,
  pareto: row.isParetoOptimal,
  cost: row.blendedCostUsd,
}))

if (EXPLAIN) {
  console.log(`IRT ${IRT_VERSION} as of ${asOf}: ${result.counts.scoredModels} models, ${result.counts.fittedObservations} fitted observations.`)
  console.log("\nCohorts:")
  for (const cohort of result.cohorts) {
    console.log(`  ${cohort.status.padEnd(20)} ${cohort.id.padEnd(44)} ${String(cohort.models).padStart(3)} models  ceiling ${cohort.ceilingShare}`)
  }
  console.log("\nModels:")
  for (const row of explainRows) {
    console.log(
      `  ${row.slug.padEnd(32)} index ${String(row.index).padStart(5)}  theta ${String(row.theta).padStart(7)}  se ${String(row.se).padStart(6)}  n ${String(row.n).padStart(2)}  ${row.status}${row.pareto ? "  pareto" : ""}`,
    )
  }
  process.exit(0)
}

const payload = {
  method: {
    version: IRT_VERSION,
    name: "ModelRegistry IRT",
    asOf,
    scale: IRT_SCALE,
    anchors: IRT_ANCHORS,
    source: "data/benchmarks.ts",
    independent: "Artificial Analysis",
    laboratoryFigures: "laboratory-published, versioned only",
    costMix: "3:1 input:output per 1M tokens, USD only",
    note: "A separate instrument from the ModelRegistry Score. Neither is an input to the other.",
  },
  counts: result.counts,
  cohorts: result.cohorts,
  scores: result.models,
}

const file = `/**
 * data/irt-scores.ts - GENERATED by scripts/build-irt.mjs. Do not edit.
 *
 * Regularized 2PL IRT scores, published on /irt as a separate instrument from the
 * ModelRegistry Score. The Score is not read here and is not changed by this fit.
 *
 * Deterministic: the reference date is the dataset revision and the anchors are
 * frozen, so the same observations always produce the same bytes.
 */
import type { IrtCohort, IrtModelScore } from "@/lib/irt"

export interface IrtMethod {
  version: string
  name: string
  asOf: string
  scale: { mean: number; sd: number }
  anchors: Record<string, number>
  source: string
  independent: string
  laboratoryFigures: string
  costMix: string
  note: string
}

export const IRT_METHOD: IrtMethod = ${JSON.stringify(payload.method, null, 2)}

export const IRT_COUNTS = ${JSON.stringify(payload.counts, null, 2)}

export const IRT_COHORTS: IrtCohort[] = ${JSON.stringify(payload.cohorts, null, 2)}

export const IRT_SCORES: IrtModelScore[] = ${JSON.stringify(payload.scores, null, 2)}
`

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : ""
  if (current !== file) {
    console.error("data/irt-scores.ts is stale. Run: node scripts/build-irt.mjs")
    process.exit(1)
  }
  console.log("✔ data/irt-scores.ts is current.")
  process.exit(0)
}

fs.writeFileSync(OUT, file)
console.log(
  `IRT ${IRT_VERSION}: ${result.counts.scoredModels} models scored from ${result.counts.fittedObservations} observations across ${result.counts.keptCohorts} cohorts.`,
)
console.log(`Wrote ${path.relative(ROOT, OUT)}.`)
console.log(`Top: ${result.models.slice(0, 3).map((row) => `${row.slug} ${row.index}`).join(", ")}`)
