/**
 * scripts/calibrate-meridian.js
 * Produces the frozen Meridian calibration (data/meridian-calibration.ts) from
 * the independent results in the registry.
 *
 *   node scripts/calibrate-meridian.js            report what a calibration would be, and what is uncovered
 *   node scripts/calibrate-meridian.js --check    exit 1 if any test the site scores has no calibration
 *   node scripts/calibrate-meridian.js --write    write data/meridian-calibration.ts
 *
 * When to run --write: ONLY when the evaluator publishes a new test or a new
 * suite version, or when the project deliberately starts a new calibration
 * epoch. Doing so changes every published score, so it requires a major bump of
 * MERIDIAN_VERSION in lib/meridian.ts, and the ledger must be rewritten with
 * `node scripts/test-meridian.js --write-ledger` and reviewed. Adding a model
 * never needs a new calibration, which is the point of the scale.
 */
const fs = require("fs")
const path = require("path")
const { load, ROOT } = require("./lib/ts-load")

const OUT = path.join(ROOT, "data", "meridian-calibration.ts")

const { modelsData } = load("data/models.ts")
const { INDEPENDENT_EVALUATOR } = load("data/independent-benchmarks.ts")
const meridian = load("lib/meridian.ts")
const independent = load("lib/independent.ts")

const boards = independent.toRankable(independent.buildIndependentBoards(modelsData))
const unitOf = Object.fromEntries(independent.buildIndependentBoards(modelsData).map((board) => [board.id, board.info.unit]))
const round = (value) => Number(value.toFixed(6))

// 1. Per-test constants from the readings on each board.
const tests = {}
for (const board of boards) {
  const transform = unitOf[board.id] === "percent" ? "logit" : "identity"
  const cal = meridian.calibrateTest(board.entries.map((entry) => entry.reading.value), transform, board.test)
  tests[board.id] = { transform, location: round(cal.location), scale: round(cal.scale), n: cal.n }
}

// 2. Reference composites and the pooled disagreement, from the rounded constants.
const perModel = new Map()
for (const board of boards) {
  for (const entry of board.entries) {
    const z = meridian.testZ(board.test, entry.reading.value, tests[board.id])
    const list = perModel.get(entry.model.id) ?? []
    list.push(z)
    perModel.set(entry.model.id, list)
  }
}
const rated = [...perModel.values()].filter((zs) => zs.length >= independent.MIN_INDEPENDENT_TESTS)
if (rated.length < 8) {
  console.error(`Only ${rated.length} reference models report ${independent.MIN_INDEPENDENT_TESTS}+ tests; a calibration needs at least 8.`)
  process.exit(1)
}
const composites = rated.map((zs) => meridian.composite(zs))
const mean = composites.reduce((a, b) => a + b, 0) / composites.length
const sd = Math.sqrt(composites.reduce((a, b) => a + (b - mean) ** 2, 0) / composites.length)
let numerator = 0
let degrees = 0
for (const zs of rated) {
  const m = zs.reduce((a, b) => a + b, 0) / zs.length
  numerator += zs.reduce((a, z) => a + (z - m) ** 2, 0)
  degrees += zs.length - 1
}
const noise = Math.sqrt(numerator / degrees)

const calibration = {
  version: meridian.MERIDIAN_VERSION,
  suite: INDEPENDENT_EVALUATOR.suite,
  calibratedAt: new Date().toISOString().slice(0, 10),
  tests,
  composite: { mean: round(mean), sd: round(sd) },
  noise: round(noise),
}

if (process.argv.includes("--check")) {
  const current = load("data/meridian-calibration.ts").meridianCalibration
  const missing = boards.filter((board) => !current.tests[board.id]).map((board) => board.id)
  const problems = []
  if (missing.length) problems.push(`no calibration for: ${missing.join(", ")}`)
  if (current.suite !== INDEPENDENT_EVALUATOR.suite) problems.push(`calibrated for "${current.suite}" but the data is "${INDEPENDENT_EVALUATOR.suite}"`)
  if (current.version !== meridian.MERIDIAN_VERSION) problems.push(`calibration version ${current.version} differs from MERIDIAN_VERSION ${meridian.MERIDIAN_VERSION}`)
  if (problems.length) {
    console.error("Meridian calibration is out of date:\n  - " + problems.join("\n  - "))
    process.exit(1)
  }
  console.log("Meridian calibration covers every scored test.")
  process.exit(0)
}

const body = `/**
 * data/meridian-calibration.ts
 * The frozen reference behind every Meridian score. GENERATED by
 * \`node scripts/calibrate-meridian.js --write\`; do not edit by hand.
 *
 * Adding a model never changes these numbers. They change only when the
 * evaluator publishes a new test or suite, or when a new calibration epoch is
 * declared on purpose (which bumps MERIDIAN_VERSION and rewrites the ledger).
 * Reference field: ${rated.length} current models reporting at least ${independent.MIN_INDEPENDENT_TESTS} tests on ${calibration.calibratedAt}.
 */
import type { Calibration } from "@/lib/meridian"

export const meridianCalibration: Calibration = ${JSON.stringify(calibration, null, 2).replace(/"([a-zA-Z_$][\w$]*)":/g, "$1:").replace(/"independent::(\w+)":/g, '"independent::$1":')}
`
if (process.argv.includes("--write")) {
  fs.writeFileSync(OUT, body)
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${Object.keys(tests).length} tests, ${rated.length} reference models).`)
} else {
  console.log(body)
}
